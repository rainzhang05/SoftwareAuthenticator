"""Regenerate tests/vectors/brainpool.rs using hashlib and cryptography/OpenSSL.

Run with the pinned E2E environment; stdout is a Rust source fixture.
The orders are RFC 5639 §§3.4/3.6. No pqkey or RustCrypto code is used.
"""
import hashlib
import hmac
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec

MESSAGE = bytes([0x11]) * 37 + bytes([0x22]) * 32
CURVES = (
    (256, 256, ec.BrainpoolP256R1(), hashes.SHA256(),
     int("a9fb57dba1eea9bc3e660a909d838d718c397aa3b561a6f7901e0e82974856a7", 16)),
    (384, 258, ec.BrainpoolP384R1(), hashes.SHA384(),
     int("8cb91e82a3386d280f5d6f7e50e641df152f7109ed5456b31f166e6cac0425a7cf3ab6af6b7fc3103b883202e9046565", 16)),
)


def nonce(d, order, size, message):
    """RFC 6979 §3.2; candidate rejection matters for Brainpool orders."""
    digest = getattr(hashlib, f"sha{size * 8}")
    h = digest(message).digest()
    z = int.from_bytes(h, "big") % order
    material = d.to_bytes(size, "big") + z.to_bytes(size, "big")
    v, k = b"\x01" * size, b"\x00" * size
    mac = lambda key, data: hmac.new(key, data, digest).digest()
    for marker in (b"\x00", b"\x01"):
        k = mac(k, v + marker + material)
        v = mac(k, v)
    while True:
        v = mac(k, v)
        candidate = int.from_bytes(v, "big")
        if 0 < candidate < order:
            return v
        k = mac(k, v + b"\x00")
        v = mac(k, v)


